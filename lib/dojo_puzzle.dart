class DojoPuzzle {
  DojoPuzzle._(this.level, List<int> givens, List<int> answer)
      : givens = List.unmodifiable(givens),
        answer = List.unmodifiable(answer);

  final DojoLevel level;
  final List<int> givens;
  final List<int> answer;
  DuelSize get size => level.size;

  factory DojoPuzzle.generate(DojoLevel level, Random random) {
    final seeds = _seeds[level]!;
    final (puzzle, solution) = seeds[random.nextInt(seeds.length)];
    final size = level.size;
    List<int> axis(int group) {
      final bands = List.generate(size.side ~/ group, (band) {
        return List.generate(group, (i) => band * group + i)..shuffle(random);
      })..shuffle(random);
      return bands.expand((band) => band).toList();
    }
    final rows = axis(size.boxRows);
    final columns = axis(size.boxColumns);
    final digits = [0, ...(List.generate(size.side, (i) => i + 1)..shuffle(random))];
    List<int> transform(String source) => [
      for (final row in rows)
        for (final column in columns)
          digits[source.codeUnitAt(row * size.side + column) - 48],
    ];
    return DojoPuzzle._(level, transform(puzzle), transform(solution));
  }

  bool isComplete(List<int> board) {
    if (board.length != answer.length) {
      throw ArgumentError.value(board.length, 'board.length');
    }
    for (var i = 0; i < board.length; i++) {
      if (board[i] != answer[i]) return false;
    }
    return true;
  }

  SudokuDuel duel() => SudokuDuel.dojo(size, givens, answer);
}
