"""Shared facility placements for runtime and the local visual editor."""
import json
import math
from pathlib import Path
from characters import load_catalog, commit_files

ROOT=Path(__file__).resolve().parents[2]
DATA=ROOT/'assets/facilities/rooms.json'
DART=ROOT/'lib/facility_config.g.dart'
FIXED={
 'salon':dict(label='桜の美容室',background='assets/kotohogu/salon_background_001.jpg',width=941,height=1672,owner='035_beaty'),
 'bakery':dict(label='洋菓子店',background='assets/kotohogu/backaly_background_001.png',width=937,height=1679,owner='047_patisie'),
 'community_center':dict(label='ことほぎ公民館',background='assets/kotohogu/community_center_background_001.png',width=941,height=1672,owner='031_kimono_fox'),
}

def validate(doc):
    if not isinstance(doc,dict) or set(doc)!={'version','facilities'} or type(doc['version']) is not int or doc['version']!=1:
        raise ValueError('施設データの形式が不正です')
    rooms=doc['facilities']
    if not isinstance(rooms,list) or len(rooms)!=len(FIXED) or [r.get('id') if isinstance(r,dict) else None for r in rooms]!=list(FIXED):
        raise ValueError('美容室・洋菓子店・公民館のID・順序は固定です')
    active={r['id']:r for r in load_catalog()['characters'] if not r.get('archived')}
    for room in rooms:
        expected=FIXED[room['id']]
        if set(room)!={'id','placements','spriteSize',*expected} or any(room.get(k)!=v for k,v in expected.items()):
            raise ValueError('施設名・背景・画像サイズ・開放キャラは固定です')
        size=room['spriteSize']
        if type(size) not in (int,float) or not math.isfinite(size) or not 80<=size<=400:
            raise ValueError('施設の共通キャラサイズは80〜400pxにしてください')
        rows=room['placements']
        if not isinstance(rows,list) or not 1<=len(rows)<=7:
            raise ValueError('配置キャラは店主を含めて1〜7人にしてください')
        ids=set()
        for row in rows:
            if not isinstance(row,dict) or set(row)!={'residentId','x','y'} or not isinstance(row['residentId'],str) or row['residentId'] not in active:
                raise ValueError('配置キャラは有効な住民から選んでください')
            if row['residentId'] in ids: raise ValueError('同じキャラを二重に配置できません')
            ids.add(row['residentId'])
            if any(type(row[k]) not in (int,float) or not math.isfinite(row[k]) for k in ('x','y')):
                raise ValueError('位置と大きさは数値で入力してください')
            x,y=row['x'],row['y']
            if not 80<=size<=400 or x<0 or y<0 or x+size>room['width'] or y+size>room['height']:
                raise ValueError('キャラ全体が背景内に収まる位置にしてください')
        if room['owner'] not in ids: raise ValueError('開放条件の店主は配置から外せません')
    return doc

def load():
    return validate(json.loads(DATA.read_text(encoding='utf-8')))

def generated(doc):
    data=json.dumps(json.dumps(doc,ensure_ascii=False),ensure_ascii=False).replace('$',r'\$')
    return "// Generated by the facility CMS. Edit assets/facilities/rooms.json.\nimport 'dart:convert';\nfinal Map<String, dynamic> facilityConfig = jsonDecode("+data+") as Map<String, dynamic>;\n"

def save(doc):
    validate(doc)
    commit_files({DATA:json.dumps(doc,ensure_ascii=False,indent=2)+'\n',DART:generated(doc)})
